import { apiFetch } from './api.js'

const post = (path, body) => apiFetch(path, { method: 'POST', body })
export const orgOverview = () => apiFetch('/api/org/overview')
export const orgGroups = () => apiFetch('/api/org/groups')
export const createGroup = (b) => post('/api/org/groups', b)
export const orgEvents = () => apiFetch('/api/org/events')
export const createEvent = (b) => post('/api/org/events', b)
export const cancelEvent = (id) => post(`/api/org/events/${id}/cancel`)
export const eventRegistrations = (id) => apiFetch(`/api/org/events/${id}/registrations`)
export const orgUpdates = () => apiFetch('/api/org/updates')
export const publishUpdate = (b) => post('/api/org/updates', b)
export const orgOpportunities = () => apiFetch('/api/org/opportunities')
export const orgMembers = () => apiFetch('/api/org/members')
export const orgInvites = () => apiFetch('/api/org/invites')
export const inviteMember = (b) => post('/api/org/invites', b)
export const revokeInvite = (code) => apiFetch(`/api/org/invites/${code}`, { method: 'DELETE' })
export const setMemberRole = (uid, role) => apiFetch(`/api/org/members/${uid}`, { method: 'PATCH', body: { role } })
export const removeMember = (uid) => apiFetch(`/api/org/members/${uid}`, { method: 'DELETE' })
